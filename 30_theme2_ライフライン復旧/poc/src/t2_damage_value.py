# --- 濁川の泥流総量の諸元（蔵王計画 表2-13/2-14）。積雪への感度を分離して測るために使う ---
# 泥流総量 = 0.4 × 融雪水量 / (0.4 − Cd)、融雪水量 = min(融雪可能水量, 積雪水量) + 御釜の湛水量
NIGORIKAWA = {
    "水蒸気爆発期": {"融雪可能水量": 13_250, "積雪水量": 935, "御釜": 1_300, "Cd": 0.076, "公表泥流総量": 2_759},
    "マグマ噴火期": {"融雪可能水量": 32_676, "積雪水量": 3_578, "御釜": 1_300, "Cd": 0.076, "公表泥流総量": 6_022},
}
# 積雪の想定の合理的な幅。0.29＝防災科研・新潟大の現地測量による流域平均／計画値、
# 1.9＝年最深積雪のGumbel 100年確率が平年値の約2.0倍（01_検討経緯.md 8.4/8.5節）
SNOW_RANGE = (0.29, 1.9)


def kateiyohin_damage(setai, depth_class):
    """家庭用品被害額（千円）。マニュアルの式そのまま: 世帯数 × 評価額 × 被害率。

    マニュアルは「メッシュ内の階数分布を用いて補正した資産額」に被害率を乗じるとしているが、
    補正係数は平均階数が3未満なら 1.0 である（表3.5.1 の留意事項）。濁川の氾濫域の平均階数は
    確認していないので **補正なし＝1.0** で計算する。3階以上が多い区域なら過大になる。
    """
    excl_car = setai * KATEIYOHIN_EXCL_CAR * RATE_KATEIYOHIN[depth_class]
    car = setai * KATEIYOHIN_CAR * RATE_CAR[depth_class]
    return {"自動車以外": excl_car, "自動車": car, "計": excl_car + car}


def lahar_total(melt_possible, swe, caldera_lake, cd):
    """泥流総量（千m³）。蔵王計画の算定を整理した式（8.4節。公表8値を誤差0.44%以内で再現）。"""
    melt = min(melt_possible, swe) + caldera_lake
    return 0.4 * melt / (0.4 - cd)


def snow_sensitivity():
    """**積雪だけに帰属する感度**を測る。2ケースの差（2.18倍）は噴火規模の差なので使えない。

    測り方は2つ:
      (1) 各ケースの積雪水量に SNOW_RANGE を当てて泥流総量が何倍動くか
      (2) マグマ噴火期に現地測量の積雪（計画値の29%）を当てると、計画自身の
          水蒸気爆発期の泥流総量と並ぶか ← **提出物⑤と図4が使っているのはこちら**
    """
    out = {}
    for name, d in NIGORIKAWA.items():
        base = lahar_total(d["融雪可能水量"], d["積雪水量"], d["御釜"], d["Cd"])
        lo = lahar_total(d["融雪可能水量"], d["積雪水量"] * SNOW_RANGE[0], d["御釜"], d["Cd"])
        hi = lahar_total(d["融雪可能水量"], d["積雪水量"] * SNOW_RANGE[1], d["御釜"], d["Cd"])
        out[name] = {
            "公表泥流総量_千m3": d["公表泥流総量"],
            "式で再現した泥流総量_千m3": round(base),
            "再現誤差_percent": round(100 * (base - d["公表泥流総量"]) / d["公表泥流総量"], 2),
            f"積雪{SNOW_RANGE[0]}倍_千m3": round(lo),
            f"積雪{SNOW_RANGE[1]}倍_千m3": round(hi),
            "積雪の幅だけで動く倍率": round(hi / lo, 2),
        }
    m = NIGORIKAWA["マグマ噴火期"]
    measured = lahar_total(m["融雪可能水量"], m["積雪水量"] * SNOW_RANGE[0], m["御釜"], m["Cd"])
    out["提出物が使う言い方"] = {
        "内容": "マグマ噴火期の想定に現地測量の積雪（計画値の29%）を当てると、泥流総量は"
                "計画自身の水蒸気爆発期と同水準に落ちる",
        "マグマ噴火期_公表_千m3": m["公表泥流総量"],
        "実測積雪を当てた場合_千m3": round(measured),
        "水蒸気爆発期_公表_千m3": NIGORIKAWA["水蒸気爆発期"]["公表泥流総量"],
        "差_percent": round(100 * (measured - NIGORIKAWA["水蒸気爆発期"]["公表泥流総量"])
                            / NIGORIKAWA["水蒸気爆発期"]["公表泥流総量"], 1),
        "したがって": "対策の物量は計画が水蒸気爆発期に割り当てている側（堤防嵩上げ11.0km、"
                      "大型土のう36,600個、総作業日数256日、氾濫範囲347世帯、対策期間30日）になる",
    }
    return out


