# --- 原単位（千円）。治水経済調査マニュアル(案) 各種資産評価単価 令和7年6月改正・令和5年評価額 ---
KATEIYOHIN_EXCL_CAR = 9_368   # 第2表 1世帯当たり家庭用品評価額（自動車以外）千円/世帯
KATEIYOHIN_CAR = 3_502        # 第2表 1世帯当たり家庭用品評価額（自動車）    千円/世帯
KAOKU_PER_M2 = {"山形": 240.1, "宮城": 242.7}  # 第1表 家屋1m²当たり評価額 千円/m²（参考。下は未使用）

# --- 被害率。砂防事業の費用便益分析マニュアル 令和8年2月 ---
# 表3.5.1 自動車を除く家庭用品の「土砂堆積（床上）」被害率
RATE_KATEIYOHIN = {"堆積50cm未満": 0.500, "堆積50cm以上": 0.845}
# 表3.5.2 自動車の被害率は「地盤面からの高さ」で決まる。泥流の堆積は70cm以上を上限側に採る
RATE_CAR = {"堆積50cm未満": 0.5, "堆積50cm以上": 1.0}   # 50〜69cm=0.5、70cm以上=1
# 表3.4 家屋の「土砂堆積（床上）」被害率（家屋被害額は床面積が無いので未計算。記録のみ）
RATE_KAOKU = {"堆積50cm未満": 0.430, "堆積50cm以上": 0.785}
# 表3.9.1 公共土木・公益施設被害額の一般資産被害額に対する比率（％）
KOKYO_RATIO = {"道路": 62.8, "橋梁": 3.7, "下水道": 0.7, "都市施設": 0.7, "公益": 6.3}
KOKYO_TOTAL = 74.2  # 小計（原文の値。内訳の和と一致する）

# --- 蔵王山 濁川の2ケース ---
