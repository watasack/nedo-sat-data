#!/usr/bin/env python3
"""S1/S2/S3 の検知可能性スクリーニング（乱数なし＝再現可能）

`18_テーマ代替案の検討.md` 4.4節の生存3件について、**外部情報を待たずに自前計算で殺せる部分**を詰める。
このプロジェクトの手法「深掘り前に自前計算で殺す」（河道閉塞案で初めて成功した運用）をそのまま当てる。

**ここで判定するのは型②（物理を精密に解くと信号が消える）だけである。**
例外(a)（同一顧客市場で商用展開済み）は外部取得（`fetch_s123_refs.py`）の担当で、ここでは扱わない。

出力: `poc/out/s123_screen.json`
"""

import json
from pathlib import Path

OUT = Path(__file__).resolve().parents[1] / "out"

# --- センサ諸元（確定値） ---------------------------------------------------
S2_GSD = 10.0          # Sentinel-2 可視・近赤外の地上分解能 [m]
S2_PIXEL_AREA = S2_GSD ** 2   # 100 m²/画素
S2_REVISIT_DAYS = 5    # 2機体制の再訪 [日]

# NDVI の観測ノイズ。大気補正後の L2A で、時系列の残差標準偏差として保守的に置く。
# **仮定**（一次出典なし。0.02〜0.05 の範囲で振って結論が変わらないことを下で確認する）
NDVI_NOISE = 0.05

# 検出に要する画素数。t検定的に、面平均のノイズは 1/sqrt(N) で下がるので
# 必要画素数 N >= (k * noise / signal)^2 、k=3（3σ）で置く
K_SIGMA = 3.0


def required_pixels(signal: float, noise: float = NDVI_NOISE, k: float = K_SIGMA) -> float:
    """面平均で信号を k σ で検出するのに要する画素数"""
    return (k * noise / signal) ** 2


def area_for_pixels(n_pixels: float) -> float:
    return n_pixels * S2_PIXEL_AREA


results = {}

# =============================================================================
# S3: 再エネ設備の管理不全（除草されていない状態の検知）
# =============================================================================
# 信号: 敷地内の植生繁茂。管理された設備は夏季に除草されるので敷地平均NDVIが低い。
#       管理不全だと法面・パネル間・パネル上に植生が乗り、敷地平均NDVIが上がる。
# **仮定**: 管理済み 0.15 / 管理不全 0.45（差 0.30）。パネル自体は低NDVIなので
#          混合画素でも差は保たれる。この差は下で 0.10 まで落として感度を見る。
s3 = {}
for label, signal in [("保守的(差0.10)", 0.10), ("中央(差0.20)", 0.20), ("想定(差0.30)", 0.30)]:
    n = required_pixels(signal)
    s3[label] = {
        "signal_ndvi": signal,
        "required_pixels": round(n, 2),
        "required_area_m2": round(area_for_pixels(n), 1),
    }

# 設備容量 → 敷地面積 → 画素数
# **仮定**: 事業用の野立ては 1MW あたり 1.0〜2.0 ha（10,000〜20,000 m²）。
#          これは業界の目安で、一次出典は未取得。下限側（1.0 ha/MW）で計算する＝厳しい側
HA_PER_MW = 1.0
s3_capacity = {}
for kw in [10, 50, 100, 500, 1000, 2000]:
    area = (kw / 1000.0) * HA_PER_MW * 10000.0   # m²
    s3_capacity[f"{kw}kW"] = {
        "site_area_m2": round(area, 1),
        "pixels": round(area / S2_PIXEL_AREA, 2),
    }

# 判定: 最も厳しい条件（信号差0.10）で要求される画素数を、どの容量帯が満たすか
threshold_px = required_pixels(0.10)
s3_min_kw = None
for kw in [10, 50, 100, 500, 1000, 2000]:
    if s3_capacity[f"{kw}kW"]["pixels"] >= threshold_px:
        s3_min_kw = kw
        break

results["S3_再エネ設備の管理不全"] = {
    "question": "除草されていない状態を Sentinel-2 の敷地平均NDVIで検出できるか",
    "detection": s3,
    "capacity_to_pixels": s3_capacity,
    "threshold_pixels_worst_case": round(threshold_px, 2),
    "min_capacity_kw_worst_case": s3_min_kw,
    "verdict": (
        f"最悪条件（NDVI差0.10・ノイズ0.05・3σ）でも {round(threshold_px,1)} 画素で足り、"
        f"{s3_min_kw}kW 以上の野立て設備がこれを満たす。型②はクリア。"
        "ただし屋根置き・小規模は対象外になるので、商品の母数は事業用の野立てに限られる"
    ),
    "unresolved": [
        "対象母数（野立て事業用設備の件数と容量分布）は FIT 認定情報から数える必要がある。未取得",
        "1MWあたりの敷地面積（1.0〜2.0 ha）に一次出典が無い。ここでは厳しい側1.0 haで計算した",
        "柵塀・標識の有無は10m画素では判定できない。商品は『植生繁茂・法面の変状』に絞る必要がある",
    ],
}

# =============================================================================
# S1: 無許可盛土・違法造成（土地改変の検知）
# =============================================================================
# 信号: 造成は植生・舗装 → 裸地。NDVI 差は大きい（0.5前後）。
# **したがって検知そのものは容易で、律速は「規制対象の規模が何画素になるか」である。**
s1 = {}
for label, signal in [("保守的(差0.20)", 0.20), ("想定(差0.50)", 0.50)]:
    n = required_pixels(signal)
    s1[label] = {
        "signal_ndvi": signal,
        "required_pixels": round(n, 2),
        "required_area_m2": round(area_for_pixels(n), 1),
    }

# 規制対象の規模（**要確認**: 盛土規制法の許可対象規模は条文で確認すること。
# ここでは「面積500m²超」という広く使われる目安を仮に置き、感度として300〜3,000m²を並べる）
s1_scale = {}
for area in [300, 500, 1000, 3000, 10000]:
    s1_scale[f"{area}m2"] = {"pixels": round(area / S2_PIXEL_AREA, 2)}

results["S1_無許可盛土_違法造成"] = {
    "question": "規制対象規模の造成を Sentinel-2 の変化検知で拾えるか",
    "detection": s1,
    "scale_to_pixels": s1_scale,
    "verdict": (
        "造成の信号（植生→裸地）はNDVI差0.5前後で大きく、保守側の0.20でも 0.6画素で足りる。"
        "面積500m²＝5画素あるので検知は成立する。型②はクリア。"
        "**ただし『盛土か切土か』『規制対象の高さか』は光学単独では判別できない**——"
        "商品は『土地改変の検知＋許可台帳との突合＝要確認リストの生成』までであり、"
        "規制の当てはめそのものは自治体の現地確認に残る"
    ),
    "unresolved": [
        "盛土規制法の許可対象規模（面積・高さ）を条文で確認すること。未取得",
        "高さの判別にはDSM差分が要るが、無償で高頻度のDSMは無い",
        "誤検知の母数（通常の工事・農地の耕起・資材置場）が実運用の律速になる。要PoC",
    ],
}

# =============================================================================
# S2: 河道内樹木の繁茂
# =============================================================================
# 信号: 樹木の面積拡大は見える。**問題は、流下能力に効くのは面積ではなく粗度係数で、**
#       **粗度係数は樹高と密度（幹の本数密度）で決まることである。**
# NDVI は密な樹冠で飽和するので、面積が同じまま「太る」変化は見えない。
s2 = {
    "area_change_detectable": True,
    "note_ndvi_saturation": (
        "樹冠が閉じるとNDVIは0.8前後で飽和し、以後の樹高・密度の増加に応答しない。"
        "面積の拡大は見えるが、同一面積内での成長は見えない"
    ),
    "what_the_customer_needs": (
        "伐採の優先順位づけには『どれだけ流下能力を下げているか』が要り、"
        "それは粗度係数＝樹高と幹の本数密度で決まる。面積だけでは代替にならない"
    ),
}

results["S2_河道内樹木"] = {
    "question": "流下能力に効く量（粗度係数）を光学衛星で出せるか",
    "analysis": s2,
    "verdict": (
        "**型②に当たる。** 面積の拡大は検知できるが、顧客の意思決定（伐採の優先順位と"
        "流下能力の再評価）に効くのは樹高と密度であり、光学のNDVIは樹冠が閉じた時点で飽和して"
        "そこに応答しない。**優位として掲げた『頻度』は、答えられない量を高頻度で出すことになる。**"
        "成立させるには樹高が要る＝航空レーザか衛星ステレオで、"
        "**それは国交省が既にやっている手段そのもの**なので優位が消える"
    ),
    "unresolved": [
        "国交省の航空レーザ測量の周期と範囲（未取得。密なら優位が完全に消える）",
    ],
}

OUT.mkdir(parents=True, exist_ok=True)
(OUT / "s123_screen.json").write_text(
    json.dumps(results, ensure_ascii=False, indent=2), encoding="utf-8")

for key, val in results.items():
    print(f"\n=== {key} ===")
    print(val["verdict"])

print(f"\n書き出し: {OUT / 's123_screen.json'}")
