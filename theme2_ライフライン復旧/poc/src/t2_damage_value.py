#!/usr/bin/env python3
"""テーマ2 未解決C ── 下流被害額を、公表原単位で金額に換算する。

**この計算の役割**: `13_事業計画の裏付け.md` 8節が「原単位が無くても物量で語れる。原単位が
取れたら掛けるだけでよい状態にしてある」と書いた、その掛け算をやる。
効くのは設問⑤の社会的インパクトと、2次審査で飛ぶ #7「ビジネス的なインパクト」・
#8「経済における定量的価値」（`13` 10節）。

**推測値を置かない設計**（`../../CLAUDE.md` の書き方の約束）:

  - 原単位も被害率も **国交省の公表マニュアルの数値をそのまま使う**。丸めない
  - 被害率は堆積深の階級で2通りあるので **1点に決めず両方出す**（泥流の堆積深は未知）
  - **家屋被害額は計算しない**。マニュアルの式が床面積を要求しており、その公表統計を
    一次情報として取得できていないため（下の UNRESOLVED）。**「家屋を含まない下限」として扱う**

入力の出典（すべて Actions 迂回で取得。原本は `origin/policy-refs` / `origin/policy-refs2`）:

  原単位  治水経済調査マニュアル(案)「各種資産評価単価及びデフレーター」令和7年6月改正
          （令和5年評価額）第1表・第2表
          https://www.mlit.go.jp/river/basic_info/seisaku_hyouka/gaiyou/hyouka/pdf/shisan_r7.pdf
  被害率  砂防事業の費用便益分析マニュアル 令和8年2月 国土交通省 水管理・国土保全局 砂防部
          表3.4（家屋）・表3.5.1（自動車を除く家庭用品）・表3.5.2（自動車）・表3.9.1（公共土木）
          https://www.mlit.go.jp/river/sabo/zigyo_hyokasyuho/r802/manualsabo.pdf
  世帯数  蔵王山噴火緊急減災対策砂防計画(案) 表4-5／表4-6（濁川。緊急対策実施前の現況）
          https://www.thr.mlit.go.jp/shinjyou/03_sabou/kazan-funka/zao/03/zao_02_05_doc.pdf
          注記に「世帯数はH22国勢調査の地域メッシュ統計から集計した参考数値」とある

出力: `../out/t2_damage_value.json`（所要1秒未満・乱数なし＝バイト単位で再現）
実行: python3 poc/src/t2_damage_value.py
"""
import json
from pathlib import Path

OUT = Path(__file__).resolve().parents[1] / "out" / "t2_damage_value.json"

# --- 原単位（千円）。治水経済調査マニュアル(案) 各種資産評価単価 令和7年6月改正・令和5年評価額 ---
KATEIYOHIN_EXCL_CAR = 9_368   # 第2表 1世帯当たり家庭用品評価額（自動車以外）千円/世帯
KATEIYOHIN_CAR = 3_502        # 第2表 1世帯当たり家庭用品評価額（自動車）    千円/世帯
KAOKU_PER_M2 = {"山形": 240.1, "宮城": 242.7}  # 第1表 家屋1m²当たり評価額 千円/m²（参考。下は未使用）

# --- 被害率。砂防事業の費用便益分析マニュアル 令和8年2月 ---
# 表3.5.1 自動車を除く家庭用品の「土砂堆積（床上）」被害率
RATE_KATEIYOHIN = {"堆積50cm未満": 0.500, "堆積50cm以上": 0.845}
# 表3.5.2 自動車の被害率は「地盤面からの高さ」で決まる。泥流の堆積は70cm以上を上限側に採る
RATE_CAR = {"堆積50cm未満": 0.5, "堆積50cm以上": 1.0}   # 50〜69cm=0.5、70cm以上=1
# 表3.4 家屋の「土砂堆積（床上）」被害率（家屋被害額は床面積が無いので未計算。記録のみ）
RATE_KAOKU = {"堆積50cm未満": 0.430, "堆積50cm以上": 0.785}
# 表3.9.1 公共土木・公益施設被害額の一般資産被害額に対する比率（％）
KOKYO_RATIO = {"道路": 62.8, "橋梁": 3.7, "下水道": 0.7, "都市施設": 0.7, "公益": 6.3}
KOKYO_TOTAL = 74.2  # 小計（原文の値。内訳の和と一致する）

# --- 蔵王山 濁川の2ケース（同じ噴火規模で積雪の想定だけが違う）---
CASES = {
    "小さい想定": {"氾濫面積km2": 8.1, "氾濫範囲世帯数": 347, "床上浸水世帯数": 133,
                   "堤防嵩上げkm": 11.0, "大型土のう個": 36_600, "総作業日数": 256, "対策期間日": 30},
    "大きい想定": {"氾濫面積km2": 14.7, "氾濫範囲世帯数": 803, "床上浸水世帯数": 356,
                   "堤防嵩上げkm": 20.6, "大型土のう個": 78_700, "総作業日数": 518, "対策期間日": 50},
}


def kateiyohin_damage(setai, depth_class):
    """家庭用品被害額（千円）。マニュアルの式そのまま: 世帯数 × 評価額 × 被害率。

    マニュアルは「メッシュ内の階数分布を用いて補正した資産額」に被害率を乗じるとしているが、
    補正係数は平均階数が3未満なら 1.0 である（表3.5.1 の留意事項）。濁川の氾濫域の平均階数は
    確認していないので **補正なし＝1.0** で計算する。3階以上が多い区域なら過大になる。
    """
    excl_car = setai * KATEIYOHIN_EXCL_CAR * RATE_KATEIYOHIN[depth_class]
    car = setai * KATEIYOHIN_CAR * RATE_CAR[depth_class]
    return {"自動車以外": excl_car, "自動車": car, "計": excl_car + car}


def main():
    res = {
        "目的": "積雪の想定違いが下流で動かす金額の下限を、公表原単位で出す",
        "出典": {
            "原単位": "治水経済調査マニュアル(案) 各種資産評価単価及びデフレーター "
                      "令和7年6月改正（令和5年評価額）第1表・第2表",
            "被害率": "砂防事業の費用便益分析マニュアル 令和8年2月 "
                      "国土交通省 水管理・国土保全局 砂防部 表3.4/3.5.1/3.5.2/3.9.1",
            "世帯数": "蔵王山噴火緊急減災対策砂防計画(案) 表4-5/表4-6（濁川・現況）",
        },
        "原単位": {
            "1世帯当たり家庭用品評価額_千円": {"自動車以外": KATEIYOHIN_EXCL_CAR, "自動車": KATEIYOHIN_CAR},
            "家屋1m2当たり評価額_千円": KAOKU_PER_M2,
            "被害率_家庭用品_土砂堆積床上": RATE_KATEIYOHIN,
            "被害率_自動車": RATE_CAR,
            "被害率_家屋_土砂堆積床上": RATE_KAOKU,
            "公共土木_一般資産比_percent": KOKYO_RATIO,
            "公共土木_小計_percent": KOKYO_TOTAL,
        },
        "ケース": {},
    }

    for depth in ("堆積50cm未満", "堆積50cm以上"):
        block = {}
        for name, c in CASES.items():
            d = kateiyohin_damage(c["床上浸水世帯数"], depth)
            # 公共土木・公益施設は一般資産被害額に比率を掛けて出す。ここでの「一般資産」は
            # 家庭用品だけなので、公共土木側も同じだけ過小になる。下限であることを名前で示す
            kokyo = d["計"] * KOKYO_TOTAL / 100.0
            block[name] = {
                "床上浸水世帯数": c["床上浸水世帯数"],
                "家庭用品被害額_億円": round(d["計"] / 100_000, 2),
                "公共土木等被害額_下限_億円": round(kokyo / 100_000, 2),
                "合計_下限_億円": round((d["計"] + kokyo) / 100_000, 2),
            }
        diff = block["大きい想定"]["合計_下限_億円"] - block["小さい想定"]["合計_下限_億円"]
        block["想定違いが動かす額_下限_億円"] = round(diff, 2)
        block["倍率"] = round(block["大きい想定"]["合計_下限_億円"]
                              / block["小さい想定"]["合計_下限_億円"], 2)
        res["ケース"][depth] = block

    # 参照値: 火山砂防事業が実際にいくらの便益で評価されているか（本計算とは独立の公表値）
    res["公表されている火山砂防事業の評価"] = {
        "浅間山直轄火山砂防事業": {
            "評価": "平成28年度 再評価（関東地方整備局 事業評価監視委員会 資料2-2-①）",
            "全体事業": {"総費用_億円": 224, "総便益_億円": 711, "BC": 3.2},
            "残事業": {"総費用_億円": 150, "総便益_億円": 550, "BC": 3.7},
            "中規模噴火の被害想定": "資産約700億円・家屋約9,000戸。国道18号・北陸新幹線・"
                                    "上信越自動車道に及ぶ",
            "便益の算出方法": "確率規模別に想定氾濫区域の被害額を算出し、確率規模別の被害軽減額に"
                              "生起確率を乗じて計画規模まで累計した年平均被害軽減期待額",
        },
        "富士山直轄砂防事業": {"全体事業_総便益_億円": 1929, "残事業_総便益_億円": 1680},
        "含意": "融雪型火山泥流を対象とする火山砂防事業のB/Cは「確率規模別の被害額×生起確率」の"
                "累計で決まる。その確率規模を決めるのが積雪深の年超過確率であり"
                "（火山砂防計画策定指針 令和5年3月）、本提案の成果物は計画の設計外力であると同時に"
                "事業評価の入力でもある",
    }

    res["UNRESOLVED"] = [
        "家屋被害額は計算していない。マニュアルの式が『床面積×家屋1m²当たり評価額×被害率』で、"
        "床面積の公表統計（総務省 住宅・土地統計調査 1住宅当たり延べ面積）を一次情報として"
        "取得できていない。第三者集計サイトの値は根拠に使わない。"
        "したがって本計算の金額は家屋を含まない下限である",
        "事業所償却・在庫資産、農漁家資産、農作物、間接被害（営業停止損失・応急対策費用）、"
        "人身被害も含んでいない。浅間山の事業評価はこれらをすべて計上している",
        "泥流の土砂堆積深が不明なので被害率の階級を決められない。2階級の両方を出してある",
        "氾濫域の建物平均階数を確認していないため資産額の階数補正は 1.0 とした",
    ]

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(json.dumps(res, ensure_ascii=False, indent=1))
    for depth, b in res["ケース"].items():
        print(f"[{depth}] 小さい想定 {b['小さい想定']['合計_下限_億円']}億円 → "
              f"大きい想定 {b['大きい想定']['合計_下限_億円']}億円 "
              f"（差 {b['想定違いが動かす額_下限_億円']}億円・{b['倍率']}倍）")
    print("->", OUT)


if __name__ == "__main__":
    main()
